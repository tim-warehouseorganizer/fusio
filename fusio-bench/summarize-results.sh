#!/usr/bin/env bash
# Pivot fusio-bench/results/jdk*.txt (JMH text output) into one markdown table:
# rows = benchmarks, columns = JDKs, cells = avg ms/op (± error).
#
#   ./fusio-bench/summarize-results.sh [results-dir] > fusio-bench/RESULTS.md
set -euo pipefail
dir="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/results}"

files=()
for f in "$dir"/jdk*.txt; do
  [ -f "$f" ] && files+=("$f")
done
if [ ${#files[@]} -eq 0 ]; then
  echo "no results in $dir" >&2
  exit 1
fi
# sort numerically by JDK feature version
mapfile -t files < <(printf '%s\n' "${files[@]}" | awk -F'jdk' '{ n=$NF; sub(/\.txt$/,"",n); print n "\t" $0 }' | sort -n | cut -f2)

awk '
FNR == 1 {
  label = FILENAME; sub(/.*\//, "", label); sub(/\.txt$/, "", label)
  labels[++n] = label
  intable = 0
}
/^# java:/   { v = $0; sub(/^# java: +/, "", v); sub(/ +$/, "", v); javav[label] = v }
/^# cpu:/    { cpu = $0; sub(/^# cpu: +/, "", cpu) }
/^# os:/     { os = $0; sub(/^# os: +/, "", os) }
/^# date:/   { date = $0; sub(/^# date: +/, "", date) }
/^# jvmArgs:/ { jvmargs = $0; sub(/^# jvmArgs: +/, "", jvmargs) }
/^Benchmark +Mode +Cnt/ { intable = 1; next }
intable && /^[A-Za-z][A-Za-z0-9_.]*Bench\./ {
  # CsvBench.fusio  avgt  5  42.068 ±  2.076  ms/op      (error column may be absent)
  bench = $1
  if (!(bench in seen)) { seen[bench] = 1; order[++m] = bench }
  score = $4
  err = ($5 == "±") ? $6 : ""
  cell = sprintf("%.1f", score)
  if (err != "") cell = cell " ± " sprintf("%.1f", err)
  val[bench, label] = cell
  raw[bench, label] = score
}
END {
  printf "<!-- generated by fusio-bench/summarize-results.sh — do not edit by hand -->\n\n"
  printf "Host: %s — %s. Run: %s. Values are JMH average time in ms/op (lower is better), ± is the 99.9%% CI half-width.\n\n", cpu, os, date
  printf "JDKs:\n"
  for (i = 1; i <= n; i++) printf "- **%s** — %s\n", labels[i], javav[labels[i]]
  printf "\n| benchmark |"
  for (i = 1; i <= n; i++) printf " %s |", labels[i]
  printf "\n|---|"
  for (i = 1; i <= n; i++) printf "---:|"
  printf "\n"
  for (j = 1; j <= m; j++) {
    b = order[j]
    printf "| `%s` |", b
    for (i = 1; i <= n; i++) {
      c = val[b, labels[i]]
      printf " %s |", (c == "" ? "—" : c)
    }
    printf "\n"
  }
}' "${files[@]}"
